test('两图联动缩放平移、坐标命中与重置', async ({ page }) => {
  await openChallenge(page)
  const target = page.getByLabel('目标图画布')
  const work = page.getByLabel('学生作品画布')
  await expect(target).toHaveAttribute('data-view', '1,0,0')
  await target.hover({ position: { x: 175, y: 175 } })
  await expect(page.locator('.coordinate').first()).toContainText('(0, 0) · 1 红')
  await page.mouse.wheel(0, -200)
  await expect(target).not.toHaveAttribute('data-view', '1,0,0')
  await expect.poll(async () => (await target.getAttribute('data-view')) === (await work.getAttribute('data-view'))).toBe(true)
  const before = await target.getAttribute('data-view')
  const box = (await work.boundingBox())!
  await work.scrollIntoViewIfNeeded()
  const visibleBox = (await work.boundingBox())!
  await page.mouse.move(visibleBox.x + box.width / 2, visibleBox.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(visibleBox.x + box.width / 2 + 40, visibleBox.y + box.height / 2 + 20, { steps: 5 })
  await page.mouse.up()
  await expect(work).not.toHaveAttribute('data-view', before!)
  await expect.poll(async () => (await target.getAttribute('data-view')) === (await work.getAttribute('data-view'))).toBe(true)
  await page.getByRole('button', { name: '重置视图' }).click()
  await expect(target).toHaveAttribute('data-view', '1,0,0')
  await expect(work).toHaveAttribute('data-view', '1,0,0')
  await target.hover({ position: { x: 2, y: 2 } })
  await expect(page.locator('.coordinate').first()).toContainText('画布范围外')
  await page.getByRole('button', { name: '放大视图' }).click()
  await page.getByRole('button', { name: /实心圆/ }).click()
  await expect(page.getByLabel('目标图画布')).toHaveAttribute('data-view', '1,0,0')
  await page.screenshot({ path: 'test-results/monaco-linked-canvas.png', fullPage: true })
})

test('损坏存档保留原文，确认后可恢复保存', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('pixel-code-lab.progress', '{broken'))
  await openChallenge(page)
  await expect(page.getByTestId('storage-status')).toContainText('原存档已保留')
  await writeCode(page, 'def pixel(x, y):\n    return 2')
  expect(await page.evaluate(() => localStorage.getItem('pixel-code-lab.progress'))).toBe('{broken')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '重试保存' }).click()
  await expect(page.getByTestId('storage-status')).toContainText('已保存')
  expect(JSON.parse((await page.evaluate(() => localStorage.getItem('pixel-code-lab.progress')))!).codes.square).toContain('return 2')
})

test('存储被禁用不会阻止写代码与运行', async ({ page }) => {
  await page.addInitScript(() => {
    const get = Storage.prototype.getItem
    const set = Storage.prototype.setItem
    Storage.prototype.getItem = function (key) { if (key === 'pixel-code-lab.progress') throw new DOMException('blocked', 'SecurityError'); return get.call(this, key) }
    Storage.prototype.setItem = function (key, value) { if (key === 'pixel-code-lab.progress') throw new DOMException('full', 'QuotaExceededError'); return set.call(this, key, value) }
  })
  await openChallenge(page)
  await expect(page.getByTestId('storage-status')).toContainText('保存失败')
  await writeCode(page, 'def pixel(x, y):\n    return 0')
  await expect(page.getByRole('button', { name: '运行', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.getByTestId('score')).toContainText('0.0%')
})
