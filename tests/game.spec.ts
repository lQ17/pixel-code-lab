async function openChallenge(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: '开始挑战' }).click()
  await expect(page.locator('.monaco-editor .view-lines')).toBeVisible()
}
async function writeCode(page: Page, code: string) {
  const editor = page.locator('.code-editor')
  await editor.click({ position: { x: 160, y: 50 } })
  await page.keyboard.press('ControlOrMeta+A')
  await page.keyboard.insertText(code)
}

test('存档校验与缩放坐标计算', () => {
  expect(parseProgress(null).levelId).toBe('square')
  expect(() => parseProgress('{broken')).toThrow()
  expect(() => parseProgress(JSON.stringify({ schemaVersion: 2 }))).toThrow()
  expect(hitCell(300, 300, 5, initialView)).toEqual({ col: 5, row: 5, x: 0, y: 0 })
  const zoomed = zoomView(initialView, 2, 400, 300)
  expect(hitCell(400, 300, 5, zoomed)).toEqual(hitCell(400, 300, 5, initialView))
  expect(hitCell(0, 0, 5, initialView)).toBeNull()
})

